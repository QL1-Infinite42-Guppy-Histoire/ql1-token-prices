function currentFilter() {
  const q = document.getElementById("searchBox").value.trim().toLowerCase();
  const minLiq = Number(document.getElementById("minLiq").value);
  const showLp = document.getElementById("showLp").checked;
  const divOnly = document.getElementById("showDivergeOnly").checked;
  let rows = DATA.tokens.filter((t) => {
    if (!showLp && t.isLP) return false;
    if (divOnly && !t.diverge) return false;
    if (minLiq > 0 && t.liqUsd != null && t.liqUsd < minLiq) return false;
    if (q && !(t.symbol || "").toLowerCase().includes(q) && !(t.name || "").toLowerCase().includes(q) && !t.address.includes(q)) return false;
    return true;
  });
  rows.sort((x, y) => {
    const xv = x[sortKey], yv = y[sortKey];
    if (xv == null && yv == null) return 0;
    if (xv == null) return 1;
    if (yv == null) return -1;
    return (typeof xv === "string" ? xv.localeCompare(yv) : xv - yv) * sortDir;
  });
  return rows;
}
