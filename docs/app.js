const SUB = { "0": "₀", "1": "₁", "2": "₂", "3": "₃", "4": "₄", "5": "₅", "6": "₆", "7": "₇", "8": "₈", "9": "₉" };
function fmtPrice(v) {
  if (v == null || !isFinite(v)) return "—";
  if (v === 0) return "$0";
  if (v >= 1000) return "$" + v.toLocaleString("en-US", { maximumFractionDigits: 2 });
  if (v >= 1) return "$" + v.toFixed(4);
  if (v >= 0.01) return "$" + v.toFixed(6);
  const e = Math.floor(Math.log10(v));           // v = m * 10^e, 1<=m<10
  const zeros = -e - 1;
  const sig = (v / Math.pow(10, e)).toFixed(3);  // 4 significant digits
  const sub = String(zeros).split("").map((d) => SUB[d]).join("");
  return "$0.0" + sub + sig;
}
function fmtFull(v) { return v == null ? "" : "$" + v.toPrecision(6); }
function fmtMoney(v) {
  if (v == null || !isFinite(v)) return "—";
  if (v >= 1e9) return "$" + (v / 1e9).toFixed(2) + "B";
  if (v >= 1e6) return "$" + (v / 1e6).toFixed(2) + "M";
  if (v >= 1e3) return "$" + (v / 1e3).toFixed(2) + "K";
  return "$" + v.toFixed(2);
}
function fmtNum(v) {
  if (v == null || !isFinite(v)) return "—";
  if (v >= 1e12) return (v / 1e12).toFixed(2) + "T";
  if (v >= 1e9) return (v / 1e9).toFixed(2) + "B";
  if (v >= 1e6) return (v / 1e6).toFixed(2) + "M";
  if (v >= 1e3) return (v / 1e3).toFixed(2) + "K";
  return String(Math.round(v * 100) / 100);
}
function esc(s) { return String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c])); }
function shortAddr(a) { return a ? a.slice(0, 6) + "…" + a.slice(-4) : ""; }

/* ---------- RPC helpers ---------- */
let rpcId = 0;
async function rpcBatch(url, calls) {
  const start = rpcId;
  const payload = calls.map(([to, data]) => ({ jsonrpc: "2.0", id: ++rpcId, method: "eth_call", params: [{ to, data }, "latest"] }));
  const res = await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(payload) });
  if (!res.ok) throw new Error("RPC HTTP " + res.status);
  const out = await res.json();
  const byId = {};
  for (const x of out) byId[x.id] = x.result || null;
  return calls.map((_, i) => byId[start + i + 1] || null);
}
async function rpcOne(url, to, data) { return (await rpcBatch(url, [[to, data]]))[0]; }
async function rpcBlock(url) {
  const res = await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "eth_blockNumber", params: [] }) });
  const j = await res.json(); return parseInt(j.result, 16);
}
function encAddr(a) { return a.toLowerCase().replace("0x", "").padStart(64, "0"); }
function encUint(n) { return n.toString(16).padStart(64, "0"); }
function decUint(hex) { return hex && hex !== "0x" ? BigInt(hex) : null; }
function decAddr(hex) { return hex && hex.length >= 42 ? "0x" + hex.slice(-40).toLowerCase() : null; }
function decStr(hex) {
  if (!hex || hex === "0x") return null;
  try {
    const b = hex.slice(2);
    if (b.length === 64) { // bytes32 string
      let s = "";
      for (let i = 0; i < 64; i += 2) { const c = parseInt(b.substr(i, 2), 16); if (c) s += String.fromCharCode(c); }
      return s || null;
    }
    const len = Number(BigInt("0x" + b.substr(64, 64)));
    let s = "";
    const raw = b.substr(128, len * 2);
    const bytes = [];
    for (let i = 0; i < raw.length; i += 2) bytes.push(parseInt(raw.substr(i, 2), 16));
    return new TextDecoder().decode(new Uint8Array(bytes));
  } catch (e) { return null; }
}
function bigToNum(rawBig, dec) { return rawBig == null ? null : Number(rawBig) / Math.pow(10, dec); }
function chunks(arr, n) { const out = []; for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n)); return out; }
