/* ---------- pricing engine (mirrors tools/generate_snapshot.py) ---------- */
function computePrices(pairs, meta, holdersMap, iconsMap, anchors) {
  const dec = (a) => { const m = meta.get(a); return m && m.decimals != null ? m.decimals : 18; };
  const sym = (a) => { const m = meta.get(a); return (m && m.symbol) || "?"; };
  const pairAddrs = new Set(pairs.map((p) => p.pair));
  const human = pairs.map((p) => ({
    pair: p.pair, t0: p.token0, t1: p.token1,
    r0: bigToNum(p.reserve0, dec(p.token0)) || 0, r1: bigToNum(p.reserve1, dec(p.token1)) || 0,
    lpSupply: p.lpSupplyRaw ? bigToNum(p.lpSupplyRaw, 18) : null,
  }));
  const anchorMap = new Map([
    [WQOM, { usd: anchors.qomUsd, label: L("anchorInfinite") }],
    [QUSDT, { usd: 1, label: L("anchorFixed") }], [QUSDC, { usd: 1, label: L("anchorFixed") }], [QDAI, { usd: 1, label: L("anchorFixed") }],
  ]);
  function direct(amap) {
    const best = new Map(), all = new Map();
    for (const pr of human) {
      for (const [known, unk, rk, ru] of [[pr.t0, pr.t1, pr.r0, pr.r1], [pr.t1, pr.t0, pr.r1, pr.r0]]) {
        const ka = amap.get(known);
        if (!ka || rk <= 0 || ru <= 0) continue;
        const liq = rk * ka.usd;
        if (liq < 0.5) continue;
        const cand = { usd: ka.usd * rk / ru, route: sym(unk) + "→" + sym(known), via: sym(known), liq, pair: pr.pair, reserveKnown: rk, reserveToken: ru };
        if (!all.has(unk)) all.set(unk, []);
        all.get(unk).push(cand);
        if (!best.has(unk) || liq > best.get(unk).liq) best.set(unk, cand);
      }
    }
    return { best, all };
  }
  let { best, all } = direct(anchorMap);
  for (const [a, b] of best) {
    const cs = all.get(a) || [];
    if (cs.length >= 2) {
      const ps = cs.map((c) => c.usd);
      if (Math.max(...ps) / Math.min(...ps) > 3) best.set(a, { ...b, diverge: cs.map((c) => ({ via: c.via, usd: c.usd, liq: c.liq })) });
    }
  }
  const inter = new Map(anchorMap);
  for (const [a, b] of best) if (b.liq >= 500 && !anchorMap.has(a) && !b.diverge) inter.set(a, { usd: b.usd, label: L("hop2Label") });
  const second = direct(inter);
  for (const [a, c] of second.best) if (!best.has(a) && !anchorMap.has(a)) best.set(a, { ...c, hop: 2, route: c.route + L("routeToAnchorSuffix") });
  for (const [a, av] of anchorMap) best.set(a, { usd: av.usd, route: av.label, via: L("viaAnchor"), liq: null, pair: null });
  const supply = (a) => { const m = meta.get(a); return m && m.totalSupply != null ? bigToNum(m.totalSupply, dec(a)) : null; };
  const tokens = [];
  for (const [addr, info] of best) {
    const m = meta.get(addr) || {};
    const s = supply(addr);
    tokens.push({
      address: addr, symbol: m.symbol || "?", name: m.name || "", decimals: dec(addr), totalSupply: s,
      holders: holdersMap.get(addr) != null ? holdersMap.get(addr) : null, icon: iconsMap.get(addr) || null,
      priceUsd: info.usd, priceQom: addr === WQOM ? 1 : info.usd / anchors.qomUsd,
      mcap: s != null ? info.usd * s : null, route: info.route, via: info.via || null, pair: info.pair || null,
      liqUsd: info.liq != null ? info.liq : null, hop: info.hop || 1,
      reserveKnown: info.reserveKnown != null ? info.reserveKnown : null, reserveToken: info.reserveToken != null ? info.reserveToken : null,
      diverge: info.diverge || null, isLP: pairAddrs.has(addr),
    });
  }
  const pmap = new Map(tokens.map((t) => [t.address, t.priceUsd]));
  for (const pr of human) {
    if (pmap.has(pr.pair)) continue;
    const p0 = pmap.get(pr.t0), p1 = pmap.get(pr.t1);
    if (p0 != null && p1 != null && pr.lpSupply) {
      const val = pr.r0 * p0 + pr.r1 * p1;
      if (val >= 0.5) {
        const m = meta.get(pr.pair) || {};
        tokens.push({
          address: pr.pair, symbol: m.symbol || "QSWAP-V2", name: "QomSwap LP " + sym(pr.t0) + "/" + sym(pr.t1),
          decimals: 18, totalSupply: pr.lpSupply, holders: holdersMap.get(pr.pair) != null ? holdersMap.get(pr.pair) : null,
          icon: iconsMap.get(pr.pair) || null, priceUsd: val / pr.lpSupply, priceQom: (val / pr.lpSupply) / anchors.qomUsd,
          mcap: val, route: L("lpBacked", sym(pr.t0), sym(pr.t1)), via: "LP", pair: pr.pair,
          liqUsd: val / 2, hop: 1, reserveKnown: null, reserveToken: null, diverge: null, isLP: true,
        });
      }
    }
  }
  tokens.sort((x, y) => (y.mcap || 0) - (x.mcap || 0));
  return tokens;
}

