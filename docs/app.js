async function lookupToken(address) {
  const addr = address.toLowerCase();
  if (priceMap.has(addr)) return priceMap.get(addr);
  const un = (DATA.unpriced || []).find((t) => t.address === addr);
  // token metadata
  const metaRes = await rpcBatch(QL1_RPC, [[addr, SEL.symbol], [addr, SEL.name], [addr, SEL.decimals], [addr, SEL.totalSupply], [addr, SEL.token0], [addr, SEL.token1]]);
  const symbol = decStr(metaRes[0]); const name = decStr(metaRes[1]);
  const decimals = metaRes[2] ? Number(decUint(metaRes[2])) : null;
  const totalSupplyRaw = decUint(metaRes[3]);
  if (!symbol && decimals == null && totalSupplyRaw == null) {
    throw new Error("ERC-20トークンとして読み取れませんでした（アドレスが違うか、QL1上のトークンではない可能性があります）");
  }
  const dec = decimals != null ? decimals : 18;
  const totalSupply = totalSupplyRaw != null ? bigToNum(totalSupplyRaw, dec) : null;
  let holders = un ? un.holders : null, icon = null;
  try {
    const r = await fetch(BS_API + "/tokens/" + addr);
    if (r.ok) { const j = await r.json(); holders = j.holders_count != null ? Number(j.holders_count) : holders; icon = j.icon_url || null; }
  } catch (e) { /* optional */ }
  const base = {
    address: addr, symbol: symbol || (un && un.symbol) || "?", name: name || (un && un.name) || "", decimals: dec,
    totalSupply, holders, icon, priceUsd: null, priceQom: null, mcap: null, route: null, via: null,
    pair: null, liqUsd: null, hop: 1, reserveKnown: null, reserveToken: null, diverge: null, isLP: false, custom: true,
  };
  // LP pair itself?
  const maybeT0 = decAddr(metaRes[4]); const maybeT1 = decAddr(metaRes[5]);
  if (maybeT0 && maybeT1) {
    const pairCheck = decAddr(await rpcOne(QL1_RPC, QL1_FACTORY, SEL.getPair + encAddr(maybeT0) + encAddr(maybeT1)));
    if (pairCheck === addr) {
      const raw = await rpcOne(QL1_RPC, addr, SEL.getReserves);
      if (raw) {
        const metaOf = async (a) => {
          const t = priceMap.get(a);
          if (t) return t;
          const d = await rpcOne(QL1_RPC, a, SEL.decimals);
          return { decimals: d ? Number(decUint(d)) : 18, priceUsd: null };
        };
        const m0 = await metaOf(maybeT0); const m1 = await metaOf(maybeT1);
        const r0 = bigToNum(BigInt("0x" + raw.slice(2, 66)), m0.decimals || 18) || 0;
        const r1 = bigToNum(BigInt("0x" + raw.slice(66, 130)), m1.decimals || 18) || 0;
        base.isLP = true;
        if (m0.priceUsd != null && m1.priceUsd != null && totalSupply) {
          const val = r0 * m0.priceUsd + r1 * m1.priceUsd;
          base.priceUsd = val / totalSupply;
          base.priceQom = base.priceUsd / DATA.anchors.qomUsd;
          base.mcap = val; base.liqUsd = val / 2;
          base.route = "LP裏付け（プール資産合計÷LP供給量）"; base.via = "LP"; base.pair = addr;
        } else {
          base.route = "LPトークン（裏付け側の価格が無いため価格なし）";
        }
        return finishCustom(base);
      }
    }
  }
  // pairs against known quote tokens
  const quoteAddrs = QUOTE_CANDIDATES.filter((q) => q !== addr);
  const pairRes = await rpcBatch(QL1_RPC, quoteAddrs.map((q) => [QL1_FACTORY, SEL.getPair + encAddr(addr) + encAddr(q)]));
  const existing = [];
  pairRes.forEach((r, i) => { const p = decAddr(r); if (p) existing.push({ pair: p, quote: quoteAddrs[i] }); });
  if (existing.length) {
    const calls = [];
    for (const e of existing) calls.push([e.pair, SEL.token0], [e.pair, SEL.getReserves]);
    const rs = await rpcBatch(QL1_RPC, calls);
    const cands = [];
    existing.forEach((e, i) => {
      const t0 = decAddr(rs[i * 2]); const raw = rs[i * 2 + 1];
      if (!raw) return;
      const quoteIs0 = t0 === e.quote;
      const quoteToken = priceMap.get(e.quote);
      const quoteDec = quoteToken ? quoteToken.decimals : 18;
      const rQuote = bigToNum(BigInt("0x" + (quoteIs0 ? raw.slice(2, 66) : raw.slice(66, 130))), quoteDec) || 0;
      const rTok = bigToNum(BigInt("0x" + (quoteIs0 ? raw.slice(66, 130) : raw.slice(2, 66))), dec) || 0;
      if (!quoteToken || quoteToken.priceUsd == null || rQuote <= 0 || rTok <= 0) return;
      const liq = rQuote * quoteToken.priceUsd;
      cands.push({ usd: quoteToken.priceUsd * rQuote / rTok, liq, pair: e.pair, via: quoteToken.symbol, reserveKnown: rQuote, reserveToken: rTok });
    });
    cands.sort((x, y) => y.liq - x.liq);
    if (cands.length && cands[0].liq >= 0.5) {
      const best = cands[0];
      base.priceUsd = best.usd;
      base.priceQom = best.usd / DATA.anchors.qomUsd;
      base.mcap = totalSupply != null ? best.usd * totalSupply : null;
      base.route = (base.symbol || "") + "→" + best.via + "（CA検索）";
      base.via = best.via; base.pair = best.pair; base.liqUsd = best.liq;
      base.reserveKnown = best.reserveKnown; base.reserveToken = best.reserveToken;
      if (cands.length >= 2 && Math.max(...cands.map((c) => c.usd)) / Math.min(...cands.map((c) => c.usd)) > 3) {
        base.diverge = cands.map((c) => ({ via: c.via, usd: c.usd, liq: c.liq }));
      }
    } else if (cands.length) {
      base.route = "プールはあるが流動性が $0.5 未満のため価格なし";
      base.pair = cands[0].pair;
    } else {
      base.route = "プールの相手側トークンに価格が無いため価格なし";
    }
  } else {
    base.route = "QomSwap にプールが見つかりません（価格なし）";
  }
  return finishCustom(base);
}
function finishCustom(tok) {
  customMeta.set(tok.address, { address: tok.address, symbol: tok.symbol, name: tok.name, decimals: tok.decimals, totalSupply: tok.totalSupply, holders: tok.holders, icon: tok.icon });
  if (DATA && !priceMap.has(tok.address)) { DATA.tokens.push(tok); DATA.unpriced = (DATA.unpriced || []).filter((t) => t.address !== tok.address); }
  rebuildPriceMap();
  saveLocal();
  return priceMap.get(tok.address) || tok;
}
