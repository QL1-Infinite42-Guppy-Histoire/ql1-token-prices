function addTracked(address, amount) {
  const addr = (address || "").toLowerCase();
  if (!tracked.has(addr)) tracked.set(addr, amount || "");
  else if (amount) tracked.set(addr, amount);
  saveLocal(); renderTracked();
}
function removeTracked(address) {
  tracked.delete(address.toLowerCase());
  saveLocal(); renderTracked();
}
function trackedEntries() {
  const out = [];
  for (const [addr, amount] of tracked) {
    const t = priceMap.get(addr) || customMeta.get(addr) || { address: addr, symbol: L("loadingSym"), priceUsd: null };
    const amt = amount === "" ? null : Number(amount);
    const value = amt != null && t.priceUsd != null ? amt * t.priceUsd : null;
    out.push({ t, amount, value });
  }
  out.sort((x, y) => (y.value || 0) - (x.value || 0) || (y.t.mcap || 0) - (x.t.mcap || 0));
  return out;
}
