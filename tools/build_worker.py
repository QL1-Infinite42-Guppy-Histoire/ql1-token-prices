#!/usr/bin/env python3
"""Assemble the ql1-token-prices cache Worker from docs/app.js.

The pricing logic (RPC helpers, anchor fetching, computePrices) is
extracted verbatim from the site's app.js so the server cache and the
browser's direct-read fallback can never drift apart. Worker-specific
glue (KV storage, cron refresh, HTTP serving) lives in worker/worker.js
after the /* === WORKER GLUE === */ marker; this script splices the
extracted logic in above it.

Usage: python3 tools/build_worker.py
Output: worker/dist/worker.bundle.js
"""
import re
import sys

APP = "docs/app.js"
GLUE = "worker/worker.js"
OUT = "worker/dist/worker.bundle.js"

src = open(APP).read()


def extract_fn(name):
    """Extract a top-level function (or async function) by brace matching."""
    m = re.search(r"(?:async\s+)?function\s+" + re.escape(name) + r"\s*\(", src)
    if not m:
        sys.exit("function not found in app.js: " + name)
    start = m.start()
    i = src.index("{", m.end() - 1)
    depth = 0
    j = i
    while True:
        c = src[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return src[start : j + 1]
        j += 1


def extract_const_block():
    """Constants from `const INF_RPC` through the end of the SEL object."""
    start = src.index("const INF_RPC")
    end = src.index("/* quote tokens tried")
    return src[start:end].rstrip()


parts = []
parts.append("/* GENERATED by tools/build_worker.py from docs/app.js — do not edit by hand. */")
parts.append(extract_const_block())

# rpc id counter + zero address const that live outside function bodies
for pat in [r"let rpcId = 0;", r"const ZERO_ADDR = \"0x0+\";"]:
    m = re.search(pat, src)
    parts.append(m.group(0))

# i18n stub: the worker emits the same Japanese route labels as the
# generated snapshot; the site's EN page translates fragments at render.
parts.append(
    'const L = (k, a, b) => { const D = {'
    ' anchorInfinite: "Infiniteアンカー", anchorFixed: "$1固定", hop2Label: "2段",'
    ' routeToAnchorSuffix: "→…→アンカー", viaAnchor: "アンカー",'
    ' lpBacked: (x, y) => "LP裏付け (" + x + "/" + y + ")",'
    ' errAnchorPool: "anchor pool fetch failed",'
    ' errQl1PoolMissing: "WQOM/qUSDT pool missing",'
    ' errQl1PoolReserves: "WQOM/qUSDT reserves fetch failed" };'
    " const v = D[k]; return typeof v === \"function\" ? v(a, b) : v; };"
)

for fn in [
    "encAddr", "encUint", "decUint", "decAddr", "decPair", "parseReservesRaw",
    "decStr", "bigToNum", "chunks",
    "rpcBatchOnce", "rpcBatch", "rpcOne", "rpcBlock",
    "fetchAnchors", "fetchQl1Reference", "fetchBlockscout", "computePrices",
]:
    parts.append(extract_fn(fn))

glue = open(GLUE).read()
marker = "/* === WORKER GLUE === */"
if marker not in glue:
    sys.exit("glue marker missing in " + GLUE)
parts.append(glue[glue.index(marker):])

open(OUT, "w").write("\n\n".join(parts) + "\n")
print("wrote", OUT, len("\n\n".join(parts)), "bytes")
